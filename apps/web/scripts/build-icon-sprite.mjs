// Usage: node scripts/build-icon-sprite.mjs <path to an unpacked @phosphor-icons/core@2.1.1>
// Writes app/assets/icons/sprite.svg from ICON_NAMES. The icon package is NOT a dependency:
// unpack it anywhere outside the repository (for example `npm pack @phosphor-icons/core@2.1.1`).
import { readFileSync, writeFileSync } from 'node:fs'
import { ICON_NAMES } from '../app/utils/icons.ts'

const source = process.argv[2]
if (!source) throw new Error('Pass the directory of @phosphor-icons/core')
const symbols = [...ICON_NAMES].sort().map((id) => {
  const weight = /-(bold|fill|duotone)$/.exec(id)?.[1] ?? 'regular'
  const svg = readFileSync(`${source}/assets/${weight}/${id}.svg`, 'utf8')
  const inner = svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '')
  return `<symbol id="${id}" viewBox="0 0 256 256">${inner}</symbol>`
})
writeFileSync(
  new URL('../app/assets/icons/sprite.svg', import.meta.url),
  `<svg xmlns="http://www.w3.org/2000/svg">\n<!-- Phosphor Icons 2.1.1, MIT (licenses/phosphor-icons-MIT.txt). Generated by scripts/build-icon-sprite.mjs; do not edit. -->\n${symbols.join('\n')}\n</svg>\n`,
)
console.log(`${symbols.length} symbols`)

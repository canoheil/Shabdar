CREATE TABLE moderation_rules (
  id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
  public_id CHAR(26) NOT NULL UNIQUE,
  phrase VARCHAR(120) NOT NULL,
  normalized_phrase VARCHAR(240) NOT NULL,
  dedupe_key VARCHAR(240) NOT NULL,
  match_mode ENUM('phrase','compact') NOT NULL,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  revision BIGINT UNSIGNED NOT NULL DEFAULT 1,
  created_at DATETIME(3) NOT NULL,
  updated_at DATETIME(3) NOT NULL,
  CONSTRAINT uq_moderation_rules_dedupe UNIQUE (dedupe_key),
  INDEX idx_moderation_rules_active_created (is_active, created_at, id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE comment_moderation_cases (
  id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
  comment_id BIGINT UNSIGNED NOT NULL,
  status ENUM('pending','confirmed_hidden','restored') NOT NULL,
  matched_rules JSON NOT NULL,
  cleared_rules JSON NULL,
  flagged_at DATETIME(3) NOT NULL,
  updated_at DATETIME(3) NOT NULL,
  handled_by BIGINT UNSIGNED NULL,
  handled_at DATETIME(3) NULL,
  CONSTRAINT uq_moderation_cases_comment UNIQUE (comment_id),
  CONSTRAINT fk_moderation_cases_comment FOREIGN KEY (comment_id) REFERENCES listing_comments(id) ON DELETE CASCADE,
  CONSTRAINT fk_moderation_cases_handler FOREIGN KEY (handled_by) REFERENCES users(id) ON DELETE SET NULL,
  INDEX idx_moderation_cases_status_flagged (status, flagged_at, id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE moderation_settings (
  id TINYINT PRIMARY KEY,
  revision BIGINT UNSIGNED NOT NULL,
  CONSTRAINT chk_moderation_settings_singleton CHECK (id = 1)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

